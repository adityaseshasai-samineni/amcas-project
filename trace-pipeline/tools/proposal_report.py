#!/usr/bin/env python3
"""Generate analysis/proposal_results.md from results/fullscale/{region,moe,heldout}/*/ (manifest.json and
replay_<placement>_<dram>_<scheme>.json written by 18_region.sh, 19_mapstudy.sh).
Usage: proposal_report.py FULLSCALE_RESULTS_DIR OUT_MD   (FULLSCALE_RESULTS_DIR contains region/ moe/ heldout/)
For compatibility a REGION_DIR (runs directly inside) is also accepted."""
import json
import os
import sys

BASE = ["identity", "bitrev", "xor_global"]  # default mapping + literature baselines
OURS = {"region": ["region"], "moe": ["region", "expert_hash", "expert_lin", "region_expert"]}
D, O = sys.argv[1], sys.argv[2]
root = D if os.path.isdir(os.path.join(D, "region")) or os.path.isdir(os.path.join(D, "moe")) else None
dirs = {"region": os.path.join(root, "region") if root else D}
if root:
    dirs["moe"] = os.path.join(root, "moe")
    dirs["heldout"] = os.path.join(root, "heldout")


def load(run_dir, pl, dr, pol, schemes):
    res = {}
    for s in schemes:
        f = os.path.join(run_dir, f"replay_{pl}_{dr}_{s}.json")
        if os.path.exists(f):
            for r in json.load(open(f)):
                if r["policy"] == pol:
                    res[s] = r
    return res


def runs(kind):
    d = dirs.get(kind)
    if d and os.path.isdir(d):
        for r in sorted(os.listdir(d)):
            if os.path.exists(os.path.join(d, r, "manifest.json")):
                yield r, os.path.join(d, r)


def fmt(r):
    return f"{r['hit_rate']:.3f} / {r['avg_read_latency']:.0f} / {r['cycles'] / 1e6:.2f} / {r['throughput_MBps'] / 1e3:.1f}"


out = ["# Mapping proposal: results", "",
       "Generated by `tools/proposal_report.py` from `cluster-data/results/fullscale/{region,moe,heldout}/*/`. Do not hand-edit.",
       "Ramulator 2.1, RoBaRaCoCh mapper on pre-transformed traces, saturated open-loop replay of one contiguous window of the LLC-miss stream of one decode step.",
       "DDR4: 1 channel, 2 ranks. DDR5: 16 subchannels, 256 B interleave, issue 4/cycle (absolute GB/s are upper bounds). Placement: packed = VA order, thp = random 2 MiB frames.",
       "Baselines: `identity` (default row-interleave), `bitrev` (Shao and Davis), `xor_global` (Rotaru-style GF(2) bank XOR searched on the same window). The best baseline is the one with the fewest cycles. Ours: `region` (per-class bank XOR on KV and activation granules, weights untouched), and for MoE also the expert-aware variants.",
       "Cells show row hit / read latency (cycles) / Mcycles / GB/s. `gain` = 1 - cycles(ours) / cycles(best baseline); `no gain` when it is below 0.5%.", ""]

# ---- summary table
summ = ["## Improvement over the best baseline, per condition", "",
        "| run | placement | DRAM | policy | best baseline | its hit / lat / Mcyc / GB/s | ours | hit / lat / Mcyc / GB/s | gain (cycles) | hit-rate delta | latency delta | GB/s delta |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|"]
detail = []
nogain = []
for kind in ("region", "moe"):
    for run, rd in runs(kind):
        man = json.load(open(os.path.join(rd, "manifest.json")))
        detail += [f"## {kind}/{run}", "", f"window {man['window'][0]:,} to {man['window'][1]:,} of {man['reads_total']:,} reads", "",
                   "| placement | DRAM | policy | scheme | row hit | rd latency (cycles) | Mcycles | GB/s | vs identity |", "|---|---|---|---|---|---|---|---|---|"]
        allsch = sorted({f["scheme"] for f in man["files"]}, key=lambda s: (["identity", "bitrev", "xor_global", "region"] + OURS["moe"]).index(s) if s in (["identity", "bitrev", "xor_global", "region"] + OURS["moe"]) else 99)
        for pl in ("packed", "thp"):
            for dr in ("ddr4", "ddr5"):
                for pol in ("Open", "ClosedCAP"):
                    res = load(rd, pl, dr, pol, allsch)
                    if "identity" not in res:
                        continue
                    for s in allsch:
                        if s in res:
                            r = res[s]
                            detail.append(f"| {pl} | {dr} | {pol} | {s} | {r['hit_rate']:.3f} | {r['avg_read_latency']:.1f} | {r['cycles'] / 1e6:.2f} | {r['throughput_MBps'] / 1e3:.1f} | {r['cycles'] / res['identity']['cycles']:.3f} |")
                    bs = [s for s in BASE if s in res]
                    os_ = [s for s in OURS[kind] if s in res]
                    if not os_:
                        continue
                    b = min(bs, key=lambda s: res[s]["cycles"])
                    o = min(os_, key=lambda s: res[s]["cycles"])
                    rb, ro = res[b], res[o]
                    g = 1 - ro["cycles"] / rb["cycles"]
                    summ.append(f"| {run} | {pl} | {dr} | {pol} | {b} | {fmt(rb)} | {o} | {fmt(ro)} | {g * 100:+.1f}% | {ro['hit_rate'] - rb['hit_rate']:+.3f} | "
                                f"{ro['avg_read_latency'] - rb['avg_read_latency']:+.0f} | {(ro['throughput_MBps'] / rb['throughput_MBps'] - 1) * 100:+.1f}% |")
                    if g < 0.005:
                        nogain.append(f"{run}/{pl}/{dr}/{pol}")
        detail.append("")
summ += ["", f"No gain (below 0.5% over the best baseline) in {len(nogain)} of {len(summ) - 4} conditions: " + ("; ".join(nogain) if nogain else "none") + ".", ""]

# ---- held-out
held = []
for run, rd in runs("heldout"):
    man = json.load(open(os.path.join(rd, "manifest.json")))
    held += [f"## heldout/{run}", "",
             "Matrices searched on token A (`*_train`), applied to token B; `*_self` = searched on B (in sample). Retained = (identity - train) / (identity - self) in cycles.", "",
             "| placement | DRAM | policy | identity Mcyc | xor_self | xor_train | xor retained | region_self | region_train | region retained |", "|---|---|---|---|---|---|---|---|---|---|"]
    for pl in ("packed", "thp"):
        for dr in ("ddr4", "ddr5"):
            for pol in ("Open", "ClosedCAP"):
                res = load(rd, pl, dr, pol, ["identity", "xor_self", "xor_train", "region_self", "region_train"])
                if "identity" not in res or "xor_train" not in res:
                    continue
                c = {k: v["cycles"] / 1e6 for k, v in res.items()}

                def ret(t, s):
                    gain = c["identity"] - c[s]
                    return f"{(c['identity'] - c[t]) / gain * 100:.0f}%" if abs(gain) > 0.005 * c["identity"] and t in c and s in c else "n/a (self gain < 0.5%)"
                held.append(f"| {pl} | {dr} | {pol} | {c['identity']:.2f} | {c.get('xor_self', float('nan')):.2f} | {c['xor_train']:.2f} | {ret('xor_train', 'xor_self')} | "
                            f"{c.get('region_self', float('nan')):.2f} | {c.get('region_train', float('nan')):.2f} | {ret('region_train', 'region_self')} |")
    held.append("")
open(O, "w").write("\n".join(out + summ + held + detail) + "\n")
print("wrote", O)
