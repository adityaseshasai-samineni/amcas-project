#!/usr/bin/env python3
"""Generate analysis/proposal_results.md from results/fullscale/region/*/ (manifest.json
and replay_<placement>_<dram>_<scheme>.json written by scripts/18_region.sh).
Usage: proposal_report.py REGION_DIR OUT_MD"""
import glob
import json
import os
import sys

SCHEMES = ["identity", "bitrev", "xor_global", "region"]
D, O = sys.argv[1], sys.argv[2]
out = ["# Region-aware mapping: results", "", "Generated by `tools/proposal_report.py` from `cluster-data/results/fullscale/region/*/`. Do not hand-edit.",
       "Ramulator 2.1, RoBaRaCoCh mapper on pre-transformed traces, saturated open-loop replay of a contiguous window of the LLC-miss stream.",
       "DDR4: 1 channel, 2 ranks. DDR5: 16 subchannels, 256 B interleave, issue 4/cycle. `vs best baseline` = cycles of region / cycles of the best of identity, bitrev, xor_global (below 1 is a gain).", ""]
for run in sorted(os.listdir(D)):
    mp = os.path.join(D, run, "manifest.json")
    if not os.path.exists(mp):
        continue
    man = json.load(open(mp))
    out += [f"## {run}", "", f"window {man['window'][0]:,} to {man['window'][1]:,} of {man['reads_total']:,} reads", "",
            "| placement | DRAM | policy | scheme | row hit | rd latency (cycles) | Mcycles | GB/s | vs identity | vs best baseline |", "|---|---|---|---|---|---|---|---|---|---|"]
    for pl in ("packed", "thp"):
        for dr in ("ddr4", "ddr5"):
            for pol in ("Open", "ClosedCAP"):
                res = {}
                for s in SCHEMES:
                    f = os.path.join(D, run, f"replay_{pl}_{dr}_{s}.json")
                    if os.path.exists(f):
                        for r in json.load(open(f)):
                            if r["policy"] == pol:
                                res[s] = r
                if "identity" not in res:
                    continue
                base = min(res[s]["cycles"] for s in SCHEMES[:3] if s in res)
                for s in SCHEMES:
                    if s not in res:
                        continue
                    r = res[s]
                    ex = f"{r['cycles'] / base:.3f}" if s == "region" else ""
                    out.append(f"| {pl} | {dr} | {pol} | {s} | {r['hit_rate']:.3f} | {r['avg_read_latency']:.1f} | {r['cycles'] / 1e6:.2f} | "
                               f"{r['throughput_MBps'] / 1e3:.1f} | {r['cycles'] / res['identity']['cycles']:.3f} | {ex} |")
    out += ["", "Matrices found (bank bit j ^= row bits) and in-order row hit per class tag:", ""]
    for f in man["files"]:
        if f["scheme"] in ("xor_global", "region"):
            hits = ", ".join(f"{k[-1]} {v:.3f}" for k, v in f.items() if k.startswith("inorder_hit_"))
            out.append(f"- {f['placement']}/{f['dram']}/{f['scheme']}: in-order hit {f['inorder_hit']:.3f} ({hits}); `{json.dumps(f['info'])}`")
    out.append("")
open(O, "w").write("\n".join(out) + "\n")
print("wrote", O)
