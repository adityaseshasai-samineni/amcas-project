#!/usr/bin/env python3
"""Write analysis/policy_results.md from cluster-data/results/fullscale/policy/*/replay.json.
Usage: policy_report.py [RESULTS_DIR] [OUT_MD]. Tables: per stream, condition = placement x DRAM x mapping x mode.
'vs best baseline' = cycles(policy)/cycles(best of Open, ClosedCAP, Timeout) (below 1 = gain), for HAPPY and Region.
"""
import glob, json, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else "cluster-data/results/fullscale/policy"
out = sys.argv[2] if len(sys.argv) > 2 else "analysis/policy_results.md"
BASE = ["Open", "ClosedCAP", "Timeout"]; ALL = BASE + ["HAPPY", "Region"]
L = ["# Row-buffer policy results (generated by tools/policy_report.py; do not hand-edit)", "",
     "Policies are new Ramulator 2.1 plugins (trace-pipeline/ramulator-ext): Timeout (64 idle cycles), HAPPY-style predictor (simplified, see happy.cpp), Region (close KV/other granules after 4 column accesses, open weights). Window: 4M contiguous misses of one decode token, 4 threads. `sat` = saturated LoadStore replay; `o3` = closed-loop SimpleO3 with 4 cores (16 MSHRs each, constant bubbles = instructions per read). Cycles are memory-clock cycles.", ""]
summ = []
for d in sorted(glob.glob(f"{root}/*/replay.json")):
    run = os.path.basename(os.path.dirname(d)); R = json.load(open(d))
    L += [f"## {run}", "", "| condition | policy | hit | read lat | Mcycles | GB/s | vs best baseline |", "|---|---|---|---|---|---|---|"]
    conds = sorted({(r["key"], r["mode"]) for r in R})
    for key, mode in conds:
        rs = {r["policy"]: r for r in R if r["key"] == key and r["mode"] == mode}
        if not all(p in rs for p in BASE): continue
        bp = min(BASE, key=lambda p: rs[p]["cycles"]); best = rs[bp]["cycles"]
        for p in ALL:
            if p not in rs: continue
            r = rs[p]
            tag = f" ({bp})" if p == bp else ""
            L.append(f"| {key} {mode} | {p}{tag} | {r['hit_rate']:.3f} | {r['avg_read_latency']:.0f} | {r['cycles']/1e6:.2f} | {r['throughput_MBps']/1e3:.1f} | {r['cycles']/best:.3f} |")
        for p in ("HAPPY", "Region"):
            if p in rs: summ.append((p, run, key, mode, rs[p]["cycles"] / best))
    L.append("")
L += ["## Summary: HAPPY / Region cycles relative to best baseline (min, median, max over conditions)", "", "| policy | stream | n | min | median | max |", "|---|---|---|---|---|---|"]
for p in ("HAPPY", "Region"):
    for run in sorted({s[1] for s in summ}):
        v = sorted(s[4] for s in summ if s[0] == p and s[1] == run)
        if v: L.append(f"| {p} | {run} | {len(v)} | {v[0]:.3f} | {v[len(v)//2]:.3f} | {v[-1]:.3f} |")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(L) + "\n")
print("wrote", out)
