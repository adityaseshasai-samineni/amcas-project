#!/usr/bin/env python3
"""Full-scale (DynamoRIO burst) report.

usage: fullscale_report.py RESULTS_DIR OUT_DIR
Reads RESULTS_DIR/fullscale/{drburst,drattr,region}/* and writes OUT_DIR/tables.md
plus fig_*.png. Only needs numpy/matplotlib/json; tolerates missing or partial runs.
"""
import glob
import json
import os
import re
import sys

LINE = 64
MODEL_BYTES = {  # model file sizes (bytes)
    "Qwen2.5-0.5B": 428730208,
    "Qwen2.5-7B": 3993201344 + 689872288,
    "Qwen3-30B-A3B": 18556685824,
}
# n_layer, n_head_kv, head_dim (documented fallbacks; f16 K and V)
KV_DIMS = {"Qwen2.5-0.5B": (24, 2, 64), "Qwen2.5-7B": (28, 4, 128),
           "Qwen3-30B-A3B": (48, 4, 128)}
SCHEMES = ["identity", "bitrev", "xor_global", "region"]


def jload(p):
    try:
        with open(p) as f:
            return json.load(f)
    except Exception:
        return None


def rtext(p):
    try:
        with open(p, errors="replace") as f:
            return f.read()
    except Exception:
        return ""


def model_of(name):
    n = name.lower()
    if "qwen3-30b" in n:
        return "Qwen3-30B-A3B"
    if "7b" in n:
        return "Qwen2.5-7B"
    if "05b" in n or "0.5b" in n:
        return "Qwen2.5-0.5B"
    return name


def ctx_of(d):
    m = re.search(r"prompt eval time\s*=\s*[\d.]+ ms\s*/\s*(\d+) tokens", rtext(d + "/plain.err"))
    if m:
        return int(m.group(1))
    sib = d.replace("_llsweep", "")
    if sib != d and os.path.isdir(sib):
        return ctx_of(sib)
    return None


def ctx_key(name):
    m = re.search(r"_c(\d+k)", name)
    return m.group(1) if m else "short"


def base_key(name):
    """Key joining burst and attr run dirs: strip _attr, _llsweep, _miss."""
    return re.sub(r"_(attr|llsweep|miss)", "", name)


def ll_stats(txt):
    """(Misses, Prefetch misses, size) of the LL block in a drcachesim text."""
    m = re.search(r"\nLL \(size=(\d+)[^\n]*\n((?:[ \t]+[^\n]*\n?)+)", txt)
    if not m:
        return None
    blk = m.group(2)

    def g(k):
        r = re.search(k + r":\s+([\d,]+)", blk)
        return int(r.group(1).replace(",", "")) if r else 0
    return g("Misses"), g("Prefetch misses"), int(m.group(1))


def step_of(d):
    m = re.search(r"attaching at step (\d+)", rtext(d + "/traced.err"))
    return int(m.group(1)) if m else None


def native_ms(d):
    s = step_of(d)
    t = rtext(d + "/steps_native.txt")
    if s is not None and t:
        b = re.search(r"^B %d (\d+)" % s, t, re.M)
        e = re.search(r"^E %d (\d+)" % s, t, re.M)
        if b and e:
            return (int(e.group(1)) - int(b.group(1))) / 1000.0
    m = re.search(r"\n[^\n]*\beval time =\s*([\d.]+) ms /\s+1 runs", "\n" + rtext(d + "/plain.err"))
    return float(m.group(1)) if m else None


def kv_dims(model, d):
    t = rtext(d + "/plain.err")
    def g(k):
        m = re.search(k + r"\s*=\s*(\d+)", t)
        return int(m.group(1)) if m else None
    nl, nk, hd = g("n_layer"), g("n_head_kv"), g("n_embd_head_k")
    if nl and nk and hd:
        return nl, nk, hd
    return KV_DIMS.get(model)


def kv_bytes_per_tok(model, d):
    k = kv_dims(model, d)
    return k[0] * k[1] * k[2] * 2 * 2 if k else None


def fmt(x, f="%.3g"):
    return "-" if x is None else f % x


def gb(n):
    return "-" if n is None else "%.2f" % (n / 1e9)


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    res, out = sys.argv[1], sys.argv[2]
    fs = os.path.join(res, "fullscale")
    os.makedirs(out, exist_ok=True)
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        plt = None

    bursts = {}
    for d in sorted(glob.glob(fs + "/drburst/*")):
        if os.path.isdir(d):
            bursts[os.path.basename(d)] = d
    # runs with their own trace (not LL-sweep-only dirs)
    runs = {n: d for n, d in bursts.items() if os.path.exists(d + "/basic_counts.txt")
            or os.path.exists(d + "/summary.json")}
    md = ["# Full-scale DynamoRIO burst results\n",
          "Generated by `trace-pipeline/tools/fullscale_report.py`; do not hand-edit. "
          "One decode token per run (step 1 for short prompts, step 16 after a 32k prompt, "
          "step 4 after an 8k prompt), 4 threads, cold 22 MiB 11-way LLC unless stated. "
          "DRAM reads = LL Misses + Prefetch misses at 64 B.\n"]

    # --- runs and validation / reads per token ---
    info = {}
    rows, rows2 = [], []
    for n, d in runs.items():
        mdl = model_of(n)
        ctx = ctx_of(d)
        bc = rtext(d + "/basic_counts.txt")
        m = re.search(r"(\d+) total \(fetched\) instructions", bc)
        ins = int(m.group(1)) if m else None
        pf = ll_stats(rtext(d + "/cachesim_pf.txt"))
        npf = ll_stats(rtext(d + "/cachesim_nopf.txt"))
        rd_pf = (pf[0] + pf[1]) if pf else None
        rd_np = npf[0] if npf else None
        nms = native_ms(d)
        info[n] = dict(model=mdl, ctx=ctx, reads_pf=rd_pf, reads_np=rd_np)
        sz = MODEL_BYTES.get(mdl)
        rows.append([n.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", ""), mdl, ctx,
                     "4", fmt(ins / 1e9 if ins else None, "%.3f") + "G",
                     fmt(nms, "%.0f"), step_of(d)])
        rows2.append([mdl, ctx, fmt(rd_pf / 1e6 if rd_pf else None, "%.1f"),
                      gb(rd_pf * LINE if rd_pf else None),
                      fmt(100.0 * rd_pf * LINE / sz if rd_pf and sz else None, "%.1f") + "%",
                      fmt(rd_np / 1e6 if rd_np else None, "%.1f"),
                      gb(rd_np * LINE if rd_np else None),
                      fmt(100.0 * rd_np * LINE / sz if rd_np and sz else None, "%.1f") + "%"])
    md.append("## Runs and validation\n")
    md.append("Instructions are for the traced token only (the load phase is not traced). "
              "Native ms is the untraced wall time of the same step "
              "(`steps_native.txt`). Same-text checks are recorded per run in `context.md` "
              "(all runs listed there matched untraced output).\n")
    md.append(table(["run", "model", "prompt tokens", "threads", "instr/token",
                     "native ms/step", "traced step"], rows))
    md.append("## DRAM reads per token\n")
    md.append("`pf` = with the simulated hardware prefetcher (Misses + Prefetch misses); "
              "`nopf` = demand Misses only. Share = bytes read / model file size.\n")
    md.append(table(["model", "ctx", "pf M lines", "pf GB", "pf share", "nopf M lines",
                     "nopf GB", "nopf share"], rows2))

    # measured / expected at long context
    short = {}
    for n, v in info.items():
        if v["ctx"] is not None and v["ctx"] < 100 and v["reads_pf"]:
            short[v["model"]] = v["reads_pf"] * LINE
    erows = []
    for n, v in info.items():
        if v["ctx"] and v["ctx"] > 1000 and v["reads_pf"] and v["model"] in short:
            kvb = kv_bytes_per_tok(v["model"], runs[n])
            if not kvb:
                continue
            kv = kvb * v["ctx"]
            exp = short[v["model"]] + kv
            meas = v["reads_pf"] * LINE
            erows.append([v["model"], v["ctx"], gb(short[v["model"]]), gb(kv), gb(exp),
                          gb(meas), "%.2f" % (meas / exp)])
    if erows:
        md.append("## Measured vs expected at long context\n")
        md.append("Expected = weights read at the short-context run + KV cache size "
                  "(layers x kv heads x head dim x 2 (K,V) x 2 B (f16) x context). "
                  "A ratio near 1 means the KV is read once; above 1 means re-reads "
                  "(KV does not stay in the LLC across the attention sweep).\n")
        md.append(table(["model", "ctx", "weights GB (short)", "KV GB", "expected GB",
                         "measured GB", "measured/expected"], erows))

    # --- LLC sweep ---
    sweep = {}
    for n, d in bursts.items():
        files = glob.glob(d + "/cachesim_pf*.txt")
        for f in files:
            st = ll_stats(rtext(f))
            if st:
                key = base_key(n)
                sweep.setdefault(key, {})[st[2]] = (st[0] + st[1]) * LINE
    sweep = {k: v for k, v in sweep.items() if len(v) > 1}
    if sweep:
        md.append("## LLC size sweep (DRAM GB per token, with prefetch)\n")
        sizes = sorted({s for v in sweep.values() for s in v})
        md.append(table(["run"] + ["%.0f MiB" % (s / 2**20) for s in sizes],
                        [[k.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", "")] +
                         [gb(v.get(s)) for s in sizes] for k, v in sweep.items()]))
        if plt:
            fig, ax = plt.subplots(figsize=(6.5, 4))
            for k, v in sweep.items():
                xs = sorted(v)
                ax.plot([x / 2**20 for x in xs], [v[x] / 1e9 for x in xs], "o-",
                        label="%s %s" % (model_of(k), ctx_key(k)))
            ax.set_xscale("log", base=2)
            ax.set_xlabel("simulated LLC size (MiB)")
            ax.set_ylabel("DRAM reads per token (GB)")
            ax.set_title("DRAM reads per token vs LLC size")
            ax.grid(alpha=.3)
            ax.legend(fontsize=8)
            fig.tight_layout()
            fig.savefig(out + "/fig_llc_sweep.png", dpi=130)
            plt.close(fig)

    # --- strides and offline row hit ---
    srows, hrows = [], []
    for n, d in runs.items():
        s = jload(d + "/summary.json")
        if not s:
            continue
        lab = n.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", "")
        st = s.get("stride", {})
        srows.append([lab, "merged", s.get("reads")] + [fmt(100 * st.get(k, 0), "%.1f") for k in
                     ["+1 line", "-1 line", "within 16 lines", "within 8 KiB row", "beyond"]])
        for td in sorted(glob.glob(d + "/thread_*")):
            t = jload(td + "/stride.json")
            if t:
                x = t.get("stride", {})
                srows.append([lab, os.path.basename(td)[7:], t.get("reads")] +
                             [fmt(100 * x.get(k, 0), "%.1f") for k in
                              ["+1 line", "-1 line", "within 16 lines", "within 8 KiB row", "beyond"]])
        orh = s.get("offline_row_hit", {})
        for pl, mp in orh.items():
            hrows.append([lab, pl] + [fmt(100 * mp.get(m, {}).get("hit"), "%.1f")
                                      for m in ["RoRaBaCoCh", "RoCoRaBaCh", "XOR-bank"]])
    if srows:
        md.append("## Stride of DRAM read stream (% of reads)\n")
        md.append(table(["run", "thread", "reads", "+1 line", "-1 line", "<=16 lines",
                         "within row", "beyond"], srows))
    if hrows:
        md.append("## Offline in-order open-page row hit (%, DDR4 8 KiB row, 2 ranks x 16 banks)\n")
        md.append(table(["run", "placement", "RoRaBaCoCh", "RoCoRaBaCh", "XOR-bank"], hrows))

    # --- Ramulator ---
    for fname, title in (("ramulator.json", "DDR4 1 channel"),
                         ("ramulator_ddr5x16.json", "DDR5 16 channels")):
        rr = []
        for n, d in runs.items():
            j = jload(d + "/" + fname)
            if not isinstance(j, list) or not j:
                continue
            ref = next((x for x in j if x["mapper"] == "RoBaRaCoCh" and x["policy"] == "Open"), None)
            lab = n.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", "")
            for x in j:
                tot = x["row_hits"] + x["row_misses"] + x["row_conflicts"]
                rr.append([lab, x["mapper"], x["policy"], fmt(100 * x["hit_rate"], "%.1f"),
                           fmt(100.0 * x["row_conflicts"] / tot if tot else None, "%.1f"),
                           fmt(x["avg_read_latency"], "%.0f"), x["cycles"],
                           fmt(x["throughput_MBps"] / 1000.0, "%.1f"),
                           fmt(x["cycles"] / ref["cycles"] if ref else None, "%.2f")])
        if rr:
            md.append("## Ramulator 2.1, %s (saturated, open-loop, reads only)\n" % title)
            md.append("Hit and conflict are % of reads. Latency in DRAM clocks. "
                      "Time rel = cycles / cycles(RoBaRaCoCh, Open) in the same run.\n")
            md.append(table(["run", "mapper", "policy", "hit %", "conflict %", "latency",
                             "cycles", "GB/s", "time rel"], rr))

    # --- attribution ---
    attrs = {}
    for d in sorted(glob.glob(fs + "/drattr/*")):
        a = jload(d + "/attr/attribution.json")
        if a:
            attrs[os.path.basename(d)] = a
    classes_all = ["dense weights", "expert weights", "KV cache", "activations", "unattributed"]
    if attrs:
        arows, hrows2, erows2 = [], [], []
        combos = [("VA-order packed", "RoRaBaCoCh"), ("4KiB shuffled", "RoRaBaCoCh"),
                  ("THP 2MiB shuffled", "RoRaBaCoCh"), ("THP 2MiB shuffled", "XOR-bank")]
        for n, a in attrs.items():
            lab = n.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", "")
            for c, v in a.get("classes", {}).items():
                arows.append([lab, c, "%.1f" % (v["reads"] / 1e6), "%.2f" % (v["MB"] / 1e3),
                              "%.1f" % (100 * v["share"]), v.get("tensors_touched")])
                o = a.get("offline_row_hit_by_class", {})
                hrows2.append([lab, c] + [fmt(100 * o.get("%s / %s" % cb, {}).get(c), "%.1f")
                                          for cb in combos])
            e = a.get("experts")
            if e:
                erows2.append([lab, fmt(e.get("mean_experts_touched_per_tensor"), "%.1f"),
                               fmt(e.get("mean_experts_mostly_read_per_tensor"), "%.1f"),
                               len(e.get("per_layer", {}))])
        md.append("## Attribution of DRAM reads by tensor class\n")
        md.append("From the `drattr` runs (tensor addresses dumped, reads attributed by address). "
                  "These are separate captures from the plain bursts above, so totals can differ "
                  "(see ANALYSIS_FULLSCALE.md).\n")
        md.append(table(["run", "class", "M reads", "GB", "share %", "tensors"], arows))
        md.append("### Offline row hit by class (%)\n")
        md.append(table(["run", "class"] + ["%s / %s" % cb for cb in combos], hrows2))
        if erows2:
            md.append("### Experts touched per MoE tensor\n")
            md.append(table(["run", "mean experts touched", "mean mostly read",
                             "expert tensors"], erows2))

    # --- region comparison ---
    reg = {}
    for d in sorted(glob.glob(fs + "/region/*")):
        for f in glob.glob(d + "/replay_*.json"):
            m = re.match(r"replay_(packed|thp)_(ddr4|ddr5)_(\w+)\.json", os.path.basename(f))
            j = jload(f)
            if not m or not isinstance(j, list):
                continue
            for x in j:
                if x.get("mapper") == "RoBaRaCoCh":
                    reg.setdefault(os.path.basename(d), {})[
                        (m.group(1), m.group(2), x["policy"], m.group(3))] = x
    if reg:
        md.append("## Region-aware mapping proposal (replay of remapped traces, RoBaRaCoCh)\n")
        md.append("Each remap rewrites the read stream with the named scheme "
                  "(identity = no change). Time rel = cycles / cycles(identity), same placement, "
                  "DRAM and policy; below 1 is faster.\n")
        rrows = []
        for rn, dct in reg.items():
            lab = rn.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", "")
            for pl in ("packed", "thp"):
                for dr in ("ddr4", "ddr5"):
                    for pol in ("Open", "ClosedCAP"):
                        ref = dct.get((pl, dr, pol, "identity"))
                        if not ref:
                            continue
                        row = [lab, pl, dr, pol]
                        for sc in SCHEMES:
                            x = dct.get((pl, dr, pol, sc))
                            row.append("-" if not x else "%.2f (hit %.0f%%)" % (
                                x["cycles"] / ref["cycles"], 100 * x["hit_rate"]))
                        rrows.append(row)
        md.append(table(["run", "placement", "DRAM", "policy"] + SCHEMES, rrows))
        if plt:
            fig, axes = plt.subplots(len(reg), 1, figsize=(8, 2.8 * len(reg)), squeeze=False)
            cols = ["#888888", "#d95f02", "#1b9e77", "#7570b3"]
            for ax, (rn, dct) in zip(axes[:, 0], reg.items()):
                groups = [(p, d) for p in ("packed", "thp") for d in ("ddr4", "ddr5")
                          if dct.get((p, d, "Open", "identity"))]
                w = 0.2
                for i, sc in enumerate(SCHEMES):
                    ys = []
                    for p, d in groups:
                        x, ref = dct.get((p, d, "Open", sc)), dct.get((p, d, "Open", "identity"))
                        ys.append(x["cycles"] / ref["cycles"] if x and ref else 0)
                    ax.bar([k + (i - 1.5) * w for k in range(len(groups))], ys, w,
                           label=sc, color=cols[i])
                ax.axhline(1, color="k", lw=.6)
                ax.set_xticks(range(len(groups)))
                ax.set_xticklabels(["%s / %s" % g for g in groups])
                ax.set_ylabel("time rel. identity")
                ax.set_title(rn.replace("-00001-of-00002_s1n1t4", "").replace("_s1n1t4", ""),
                             fontsize=9)
                ax.grid(axis="y", alpha=.3)
            axes[0, 0].legend(fontsize=7, ncol=4)
            fig.tight_layout()
            fig.savefig(out + "/fig_region_time.png", dpi=130)
            plt.close(fig)

    # --- figure: DRAM reads per token, stacked by class where attributed ---
    if plt and (info or attrs):
        bars = []  # (label, {class: bytes})
        for n, v in info.items():
            if v["reads_pf"]:
                bars.append(("%s\nctx %s\nburst" % (v["model"], v["ctx"]),
                             {"total (not attributed)": v["reads_pf"] * LINE}))
        for n, a in attrs.items():
            if "_miss" in n or "_early" in n:
                continue
            d = fs + "/drattr/" + n
            bars.append(("%s\nctx %s\nattr" % (model_of(n), ctx_of(d)),
                         {c: v["reads"] * LINE for c, v in a["classes"].items()}))
        if bars:
            fig, ax = plt.subplots(figsize=(max(7, 0.95 * len(bars)), 4.5))
            cl = classes_all + ["total (not attributed)"]
            colors = ["#1f77b4", "#2ca02c", "#d62728", "#ff7f0e", "#bbbbbb", "#555555"]
            bot = [0] * len(bars)
            for c, col in zip(cl, colors):
                ys = [b[1].get(c, 0) / 1e9 for b in bars]
                if any(ys):
                    ax.bar(range(len(bars)), ys, bottom=bot, label=c, color=col)
                    bot = [a + b for a, b in zip(bot, ys)]
            ax.set_xticks(range(len(bars)))
            ax.set_xticklabels([b[0] for b in bars], fontsize=7)
            ax.set_ylabel("DRAM reads per token (GB)")
            ax.set_title("DRAM reads per token (burst totals and attributed runs)")
            ax.legend(fontsize=7)
            ax.grid(axis="y", alpha=.3)
            fig.tight_layout()
            fig.savefig(out + "/fig_reads_per_token.png", dpi=130)
            plt.close(fig)

    with open(out + "/tables.md", "w") as f:
        f.write("\n".join(md))
    print("wrote", out + "/tables.md")


if __name__ == "__main__":
    main()
