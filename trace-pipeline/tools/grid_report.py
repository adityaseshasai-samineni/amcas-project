#!/usr/bin/env python3
"""Report for the mapping x row-policy x trace grid (grid-owner).

Usage: grid_report.py RESULTS_GRID_DIR OUT_DIR      (RESULTS_GRID_DIR/NAME/{replay.json,manifest.json})
Writes OUT_DIR/grid.md and OUT_DIR/grid.csv (one row per trace x placement x DRAM x mapping x policy).

Metrics: row hit rate (row_hits / all column accesses), mean read latency (Ramulator avg_read_latency, memory cycles of the
saturated open-loop replay: it includes queueing, so compare within a DRAM only), cycles (saturated replay to drain 4M reads).
Ratios are cycles (or latency) divided by the same trace's identity mapping with the Open policy (<1 is better); class tables
use the geometric mean over the class's traces. 'Oracle' = future-aware keep-open/close decision per access (Ramulator plugin,
fed with the bank's row sequence of an Open run); 'headroom' = Oracle / Open of the same mapping.
"""
import csv, json, math, os, sys
from collections import defaultdict

CLASS = {
    "att short (1k, 8k, 0.5B)": ["q7_1k", "q7_8k", "q05_short"],
    "att long-context (32k)": ["q7_32k", "q7_32k_t2", "q05_32k"],
    "att batched": ["q7_B16P512", "q7_B4P8192", "q7_B4P32768"],
    "att prefill": ["q7_pf32", "q7_ub32"],
    "MoE decode": ["q30_short", "q30_1k", "q30_32k", "q30_n4", "q30_B4P512", "q30_B16P512", "q30_B4P8192", "q30_B4P32768"],
    "MoE prefill": ["q30_pf32"],
}
MAPS = ["identity", "xor_global", "region", "chan", "xor_global_chan", "mop", "mopxor", "bitrev", "chra", "naive", "expert_hash", "expert_lin"]
POLS = ["Open", "ClosedCAP", "Timeout16", "Timeout64", "Timeout256", "Region", "HAPPY", "HAPPYcnt", "Adaptive", "Adaptive7_4", "Oracle"]
DRAMN = {"d4r6": "DDR4-2933 6ch", "x16": "DDR5-4800 16 sub-ch"}
PLN = {"packed": "packed", "thp": "2 MiB THP"}


def gm(xs):
    xs = [x for x in xs if x and x > 0]
    return math.exp(sum(map(math.log, xs)) / len(xs)) if xs else None


def f(x, p=3):
    return "-" if x is None else f"{x:.{p}f}"


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    rows, man = [], {}
    for name in sorted(os.listdir(src)):
        p = f"{src}/{name}/replay.json"
        if not os.path.exists(p):
            continue
        try:
            rs = json.load(open(p))
        except Exception:
            continue
        for r in rs:
            r["trace"] = name
            rows.append(r)
        if os.path.exists(f"{src}/{name}/manifest.json"):
            man[name] = json.load(open(f"{src}/{name}/manifest.json"))
    traces = sorted({r["trace"] for r in rows})
    D = {(r["trace"], r["placement"], r["dram"], r["mapping"], r["policy"]): r for r in rows}
    base = {(t, pl, dr): D.get((t, pl, dr, "identity", "Open")) for t in traces for pl in PLN for dr in DRAMN}
    cls_of = {t: c for c, ts in CLASS.items() for t in ts}
    # CSV
    with open(f"{out}/grid.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["trace", "class", "placement", "dram", "mapping", "policy", "reads", "cycles", "hit_rate", "miss_rate", "conflict_rate",
                    "avg_read_latency", "cycles_vs_identity_open", "latency_vs_identity_open"])
        for r in sorted(rows, key=lambda r: (r["trace"], r["dram"], r["placement"], r["mapping"], r["policy"])):
            b = base[(r["trace"], r["placement"], r["dram"])]
            w.writerow([r["trace"], cls_of.get(r["trace"], "?"), r["placement"], r["dram"], r["mapping"], r["policy"], r["reads"], r["cycles"],
                        f"{r['hit_rate']:.5f}", f"{r['miss_rate']:.5f}", f"{r['conflict_rate']:.5f}", f"{r['avg_read_latency']:.2f}",
                        f"{r['cycles'] / b['cycles']:.5f}" if b else "", f"{r['avg_read_latency'] / b['avg_read_latency']:.5f}" if b else ""])

    def cell(cl, pl, dr, mp, pol, what):
        vals = []
        for t in CLASS[cl]:
            r, b = D.get((t, pl, dr, mp, pol)), base.get((t, pl, dr))
            if r is None or b is None:
                continue
            vals.append({"hit": r["hit_rate"], "lat": r["avg_read_latency"], "cyc": r["cycles"] / b["cycles"],
                         "latr": r["avg_read_latency"] / b["avg_read_latency"]}[what])
        if not vals:
            return None, 0
        return (gm(vals) if what in ("cyc", "latr") else sum(vals) / len(vals)), len(vals)

    L = ["# Mapping x row-buffer policy x trace grid", "",
         "Generated by `tools/grid_report.py` from `cluster-data/results/fullscale/grid/*/replay.json`. Do not hand-edit.", "",
         f"Traces replayed: {len(traces)} ({', '.join(traces)}). {len(rows)} Ramulator replays. Window 4M reads from 30% of the step, saturated "
         "LoadStoreTrace, placements packed and 2 MiB THP, DDR4-2933 6 channels (validation-owner real-node model) and DDR5-4800 16 sub-channels.", "",
         "Cycles ratio = cycles / (same trace, identity mapping, Open policy); geometric mean over the class's traces (<1 is better). "
         "Hit = mean row hit rate. Lat = mean read latency (memory cycles; includes queueing in the saturated replay).", ""]
    # best combos
    L += ["## Best combination per class (lowest geometric-mean cycles ratio, realisable policies only; Oracle excluded)", "",
          "| class | DRAM | placement | best mapping + policy | cycles ratio | hit | best fixed-mapping (identity) policy | ratio | Oracle/Open (best mapping) | Oracle ratio vs identity/Open |", "|---|---|---|---|---|---|---|---|---|---|"]
    best_tab = {}
    for cl in CLASS:
        for dr in DRAMN:
            for pl in PLN:
                bst = None
                for mp in MAPS:
                    for pol in POLS[:-1]:
                        v, n = cell(cl, pl, dr, mp, pol, "cyc")
                        if v is not None and n >= max(1, len([t for t in CLASS[cl] if t in traces]) - 0) and (bst is None or v < bst[0]):
                            bst = (v, mp, pol)
                if not bst:
                    continue
                hit, _ = cell(cl, pl, dr, bst[1], bst[2], "hit")
                bi = min(((cell(cl, pl, dr, "identity", p, "cyc")[0], p) for p in POLS[:-1] if cell(cl, pl, dr, "identity", p, "cyc")[0] is not None), default=(None, "-"))
                orc_o = cell(cl, pl, dr, bst[1], "Oracle", "cyc")[0]
                opn = cell(cl, pl, dr, bst[1], "Open", "cyc")[0]
                head = orc_o / opn if (orc_o and opn) else None
                best_tab[(cl, dr, pl)] = bst
                L.append(f"| {cl} | {DRAMN[dr]} | {PLN[pl]} | {bst[1]} + {bst[2]} | {f(bst[0])} | {f(hit)} | identity + {bi[1]} | {f(bi[0])} | {f(head)} | {f(orc_o)} |")
    L.append("")
    # per class tables
    for cl in CLASS:
        ts = [t for t in CLASS[cl] if t in traces]
        if not ts:
            continue
        L += [f"## {cl}", "", f"Traces: {', '.join(ts)}", ""]
        for dr in DRAMN:
            for pl in PLN:
                L += [f"### {cl} / {DRAMN[dr]} / {PLN[pl]}", ""]
                for what, title in (("cyc", "cycles ratio vs identity/Open"), ("hit", "row hit rate"), ("lat", "mean read latency (cycles)"), ("latr", "latency ratio vs identity/Open")):
                    L += [f"**{title}**", "", "| mapping | " + " | ".join(POLS) + " |", "|---|" + "---|" * len(POLS)]
                    for mp in MAPS:
                        cells = [cell(cl, pl, dr, mp, p, what)[0] for p in POLS]
                        if all(c is None for c in cells):
                            continue
                        pr = 1 if what in ("lat",) else 3
                        L.append(f"| {mp} | " + " | ".join(f(c, pr) for c in cells) + " |")
                    L.append("")
    # oracle headroom per mapping
    L += ["## Oracle headroom over Open, per mapping (geometric mean over all traces)", "",
          "Oracle/Open cycles, Oracle/Open latency, and the offline in-order model of the same stream (hit rate; modelled mean access latency Open vs Oracle, memory cycles; "
          "conflict -> miss saves tRP).", "", "| DRAM | placement | mapping | Oracle/Open cycles | Oracle/Open latency | Oracle hit | Open hit | best realisable policy / Open cycles | which |", "|---|---|---|---|---|---|---|---|---|"]
    for dr in DRAMN:
        for pl in PLN:
            for mp in MAPS:
                rc, rl, oh, ph, bp = [], [], [], [], {}
                for t in traces:
                    o, p = D.get((t, pl, dr, mp, "Oracle")), D.get((t, pl, dr, mp, "Open"))
                    if o and p:
                        rc.append(o["cycles"] / p["cycles"]); rl.append(o["avg_read_latency"] / p["avg_read_latency"])
                        oh.append(o["hit_rate"]); ph.append(p["hit_rate"])
                        for pol in POLS[1:-1]:
                            q = D.get((t, pl, dr, mp, pol))
                            if q:
                                bp.setdefault(pol, []).append(q["cycles"] / p["cycles"])
                if not rc:
                    continue
                bpol = min(((gm(v), k) for k, v in bp.items()), default=(None, "-"))
                L.append(f"| {DRAMN[dr]} | {PLN[pl]} | {mp} | {f(gm(rc))} | {f(gm(rl))} | {f(sum(oh) / len(oh))} | {f(sum(ph) / len(ph))} | {f(bpol[0])} | {bpol[1]} |")
    L.append("")
    # offline oracle model
    L += ["## Offline in-order oracle model (per stream order, from manifest.json; mean over traces)", "",
          "| DRAM | placement | mapping | in-order Open hit | conflicts | modelled latency Open | Closed | Oracle |", "|---|---|---|---|---|---|---|---|"]
    for dr in DRAMN:
        for pl in PLN:
            for mp in MAPS:
                a = defaultdict(list)
                for t, m in man.items():
                    for c in m["combos"]:
                        if c["dram"] == dr and c["placement"] == pl and mp in c["mappings"]:
                            o = c["mappings"][mp]
                            for k in ("hit_rate", "conflict_rate", "lat_open", "lat_closed", "lat_oracle"):
                                a[k].append(o[k])
                if a["hit_rate"]:
                    mean = lambda k: sum(a[k]) / len(a[k])
                    L.append(f"| {DRAMN[dr]} | {PLN[pl]} | {mp} | {f(mean('hit_rate'))} | {f(mean('conflict_rate'))} | {f(mean('lat_open'), 1)} | {f(mean('lat_closed'), 1)} | {f(mean('lat_oracle'), 1)} |")
    L.append("")
    open(f"{out}/grid.md", "w").write("\n".join(L))
    print(f"wrote {out}/grid.md, grid.csv: {len(rows)} replays, {len(traces)} traces")


if __name__ == "__main__":
    main()
