#!/usr/bin/env python3
"""Tables from results/gpu/ds3/q7_{gpu}_{cell}_fa{fa}_ib{ib}.json (gpu_ds3_study.py): per cell, Ramulator and DRAMsim3 side by side.
usage: gpu_ds3_report.py DIR OUT.md"""
import glob, json, os, sys
D, OUT = sys.argv[1:3]
rows = {}
for f in sorted(glob.glob(f"{D}/q7_*_ib*.json")):
    b = os.path.basename(f)[:-5]; tag, ib = b.rsplit("_ib", 1)
    rows[(tag, int(ib))] = json.load(open(f))
PRM = {"ram": ("Open", "ClosedCAP"), "ds3": ("OPEN_PAGE", "CLOSE_PAGE")}
SCH = ["identity", "xor", "chan", "xor_chan"]
o = ["# GPU DRAM streams in Ramulator 2 and DRAMsim3 (generated by gpu_ds3_report.py)\n"]
best = []
for (tag, ib), d in sorted(rows.items(), key=lambda k: (k[0][0].split("_")[1], ["short", "8k", "32k"].index(k[0][0].split("_")[2]), k[0][0].split("_")[3], k[0][1])):
    R = {(r["sim"], r["scheme"], r["policy"]): r for r in d["results"]}
    o.append(f"\n### {tag}, channel interleave {'256 B' if ib == 2 else '2 KiB'} ({d['requests']/1e6:.0f} M of {d['stream_requests']/1e6:.0f} M requests, {d['reads']/1e6:.1f} M reads)\n")
    o.append("| scheme | policy (Ram / DS3) | Ram hit | Ram lat cyc / ns | Ram cycles (ratio vs identity same policy) | DS3 hit | DS3 lat cyc / ns | DS3 cycles (ratio) |\n|---|---|---|---|---|---|---|---|")
    for pi in (0, 1):
        for sc in SCH:
            a = R.get(("ram", sc, PRM["ram"][pi])); c = R.get(("ds3", sc, PRM["ds3"][pi]))
            a0 = R.get(("ram", "identity", PRM["ram"][pi])); c0 = R.get(("ds3", "identity", PRM["ds3"][pi]))
            if not a or not c: continue
            o.append(f"| {sc} | {PRM['ram'][pi]} / {PRM['ds3'][pi]} | {a['hit_rate']:.3f} | {a['avg_read_latency_cycles']:.0f} / {a['avg_read_latency_ns']:.0f} | {a['cycles']/1e6:.3f} M ({a['cycles']/a0['cycles']:.3f}) | "
                     f"{c['hit_rate']:.3f} | {c['avg_read_latency_cycles']:.0f} / {c['avg_read_latency_ns']:.0f} | {c['cycles']/1e6:.3f} M ({c['cycles']/c0['cycles']:.3f}) |")
    for sim in ("ram", "ds3"):
        k = min(((s, p) for s in SCH for p in PRM[sim]), key=lambda sp: R[(sim, sp[0], sp[1])]["cycles"] if (sim, sp[0], sp[1]) in R else 1e30)
        b2 = rows.get((tag, 2)); base = {(r["sim"], r["scheme"], r["policy"]): r for r in b2["results"]}[(sim, "identity", PRM[sim][0])]["cycles"] if b2 else float("nan")
        best.append((tag, ib, sim, k, R[(sim, k[0], k[1])]["cycles"] / R[(sim, "identity", PRM[sim][0])]["cycles"], R[(sim, k[0], k[1])]["hit_rate"], R[(sim, k[0], k[1])]["cycles"] / base))
o.append("\n## Best (scheme, policy) by cycles per cell and interleave; ratio = cycles / identity+Open of the same simulator\n\n| cell | ib | sim | best | cycles ratio (vs identity+Open at the same ib) | cycles ratio vs identity+Open at 256 B | hit |\n|---|---|---|---|---|---|---|")
for t, ib, s, k, r, h, rb in best:
    o.append(f"| {t} | {'256 B' if ib == 2 else '2 KiB'} | {s} | {k[0]} + {k[1]} | {r:.3f} | {rb:.3f} | {h:.3f} |")
open(OUT, "w").write("\n".join(o) + "\n"); print("\n".join(o[-40:]))
